<?php

declare(strict_types=1);

namespace App\Models;

use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

#[Fillable([
    'inventory_document_id',
    'product_id',
    'quantity',
    'notes',
])]
class InventoryDocumentItem extends Model
{
    use HasFactory;

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'quantity' => 'decimal:3',
        ];
    }

    /**
     * The parent inventory document.
     */
    public function document(): BelongsTo
    {
        return $this->belongsTo(InventoryDocument::class, 'inventory_document_id');
    }

    /**
     * The associated product.
     */
    public function product(): BelongsTo
    {
        return $this->belongsTo(Product::class, 'product_id');
    }

    /**
     * Stock movements generated by this item line.
     */
    public function stockMovements(): HasMany
    {
        return $this->hasMany(StockMovement::class, 'inventory_document_item_id');
    }

    protected static function booted(): void
    {
        static::deleting(function (InventoryDocumentItem $item): void {
            if ($item->stockMovements()->exists()) {
                throw new \LogicException('Cannot delete inventory document item that has historical stock movements.');
            }
        });
    }
}
